import { readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

export const DEFAULT_CATALOGUE_PATH = fileURLToPath(new URL('../CLIENTS.md', import.meta.url));
const compiledRegistryUrl = new URL('../.test-dist/client-registry.js', import.meta.url);
const cell = value => String(value).replaceAll('|', '\\|').replaceAll('\n', ' ');

/** Documentation projection of compiled current declarations, never verification. */
export function renderClientCatalogue(registry, sources, profile) {
  if (!Array.isArray(registry) || typeof profile !== 'string' || registry.length === 0) throw new Error('Compile the current client registry first');
  const names = new Set(), products = new Set();
  for (const client of registry) {
    if (typeof client.name !== 'string' || names.has(client.name) || !Array.isArray(client.products) || client.products.length === 0
      || typeof client.readerKind !== 'string' || !['ai', 'bot'].includes(client.trafficClass)
      || sources[client.source] === undefined) throw new Error('Invalid client catalogue');
    names.add(client.name);
    for (const product of client.products) {
      if (typeof product !== 'string' || products.has(product.toLowerCase())) throw new Error('Duplicate or invalid client product');
      products.add(product.toLowerCase());
    }
  }
  const rows = registry.slice().sort((a, b) => a.name < b.name ? -1 : a.name > b.name ? 1 : 0).map(client => {
    const source = sources[client.source];
    const review = source.checkedOn === null ? 'inherited catalogue; no fresh review date' : `${source.basis}; ${source.checkedOn}`;
    return `| \`${cell(client.name)}\` | ${client.products.map(product => `\`${cell(product)}\``).join(', ')} | \`${cell(client.trafficClass)}\` | \`${cell(client.readerKind)}\` | [${cell(client.source)}](${source.url}) — ${cell(review)} |`;
  });
  return `# Current client declarations

<!-- Generated by scripts/client-catalogue.mjs from the compiled client-registry module. Do not edit this table by hand. -->

Registry profile: \`${cell(profile)}\`. **${names.size} canonical names, ${products.size} exact product aliases.** This describes the checked source; it does not establish deployment, traffic incidence or authenticated identity.

A match is a lexical User-Agent declaration. Product matching is case-insensitive; aliases map to the canonical name below. Several canonical matches retain every candidate and select no single name. Compatible declarations may share a role; incompatible roles abstain. Documented roles do not prove a request's actual purpose or initiating party. Generic automation and browser/network rules are separate from this named catalogue.

The source column records the registry's evidence basis. Inherited entries retain their source pointers without claiming a fresh review. A crawler's documented role, a published address method, a signing-origin association and a reviewed key publisher are separate facts; this table does not imply that every client has those verification methods. See [method scope and evidence boundaries](README.md#verification-and-network-methods).

| Canonical name | Exact product aliases | Coarse class | Declared reader kind | Source and review basis |
| --- | --- | --- | --- | --- |
${rows.join('\n')}

Refresh after compiling the analytics test modules with \`pnpm -C packages/analytics exec tsc -p tsconfig.test.json\`, then run \`node packages/analytics/scripts/client-catalogue.mjs\` from the repository root. Run the same command with \`--check\` to reject drift without writing. The normal analytics test suite compiles first and checks this generated file. Follow the [maintainer procedure](README.md#maintaining-declarations-and-evidence-profiles) before changing the registry; imported OSS lists never become trusted runtime rules automatically.
`;
}

export async function catalogueCommand(args = process.argv.slice(2)) {
  let check = false, output = DEFAULT_CATALOGUE_PATH;
  for (let i = 0; i < args.length; i++) {
    if (args[i] === '--check' && !check) check = true;
    else if (args[i] === '--output' && typeof args[i + 1] === 'string' && !args[i + 1].startsWith('--')) output = resolve(args[++i]);
    else throw new Error('Usage: client-catalogue.mjs [--check] [--output path]');
  }
  const { CLIENT_REGISTRY, CLIENT_REGISTRY_SOURCES, CLIENT_REGISTRY_PROFILE } = await import(compiledRegistryUrl.href);
  const expected = renderClientCatalogue(CLIENT_REGISTRY, CLIENT_REGISTRY_SOURCES, CLIENT_REGISTRY_PROFILE);
  if (check) {
    const actual = await readFile(output, 'utf8');
    if (actual !== expected) throw new Error('Client catalogue is stale; compile the current registry and regenerate CLIENTS.md');
  } else await writeFile(output, expected);
  return { mode: check ? 'check' : 'write', output, profile: CLIENT_REGISTRY_PROFILE, clients: CLIENT_REGISTRY.length };
}

if (process.argv[1] !== undefined && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  try { process.stdout.write(JSON.stringify(await catalogueCommand()) + '\n'); }
  catch (error) { process.stderr.write((error instanceof Error ? error.message : 'Client catalogue generation failed') + '\n'); process.exitCode = 1; }
}
